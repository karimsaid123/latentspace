import { NextRequest, NextResponse } from 'next/server';
import { container } from '@/core/container';
import { summarizeWithGemini } from '@/lib/ai-summarizer';
import { logger } from '@/lib/logger';

export const dynamic = 'force-dynamic';
export const revalidate = 0;

export async function GET(request: NextRequest) {
  return handleSummarize(request);
}

export async function POST(request: NextRequest) {
  return handleSummarize(request);
}

async function handleSummarize(request: NextRequest) {
  const startTime = Date.now();
  let articleId: string | null = null;

  try {
    if (request.method === 'POST') {
      const body = await request.json().catch(() => ({}));
      articleId = body.articleId || body.id;
    } else {
      articleId = request.nextUrl.searchParams.get('id');
    }

    if (!articleId) {
      return NextResponse.json({ error: 'Missing articleId' }, { status: 400 });
    }

    await container.bootstrap();
    await container.syncEdgeState(false);

    const article = await container.articleRepo.findById(articleId);
    if (!article) {
      return NextResponse.json({ error: 'Article not found' }, { status: 404 });
    }

    // If already generated by Gemini, return immediately with 0 latency
    if (article.summary?.generatedWith === 'gemini') {
      return NextResponse.json({
        success: true,
        summary: article.summary,
        source: 'cache',
        durationMs: Date.now() - startTime,
      });
    }

    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return NextResponse.json({
        success: true,
        summary: article.summary,
        source: 'heuristic',
        message: 'No GEMINI_API_KEY configured',
        durationMs: Date.now() - startTime,
      });
    }

    const geminiSummary = await summarizeWithGemini(
      article.title,
      article.contentSnippet || article.title,
      apiKey
    );

    if (geminiSummary) {
      article.summary = geminiSummary;
      await container.articleRepo.saveMany([article]);

      logger.info('On-demand Gemini summary generated', {
        articleId,
        durationMs: Date.now() - startTime,
      });

      return NextResponse.json({
        success: true,
        summary: geminiSummary,
        source: 'gemini',
        durationMs: Date.now() - startTime,
      });
    }

    return NextResponse.json({
      success: true,
      summary: article.summary,
      source: 'fallback',
      durationMs: Date.now() - startTime,
    });
  } catch (err: any) {
    logger.error('Summarize endpoint error', {
      articleId,
      error: err?.message,
    });

    return NextResponse.json(
      { error: err?.message || 'Internal summarization error' },
      { status: 500 }
    );
  }
}
