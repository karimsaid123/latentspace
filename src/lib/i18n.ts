export type Locale = 'en' | 'es' | 'ar' | 'zh';

export interface LocaleConfig {
  code: Locale;
  label: string;
  nativeName: string;
  dir: 'ltr' | 'rtl';
}

export const LOCALES: Record<Locale, LocaleConfig> = {
  en: { code: 'en', label: 'EN', nativeName: 'ENGLISH', dir: 'ltr' },
  es: { code: 'es', label: 'ES', nativeName: 'ESPAÑOL', dir: 'ltr' },
  ar: { code: 'ar', label: 'AR', nativeName: 'العربية', dir: 'rtl' },
  zh: { code: 'zh', label: 'ZH', nativeName: '中文', dir: 'ltr' },
};

export const DEFAULT_LOCALE: Locale = 'en';

export function isRTL(locale: Locale): boolean {
  return LOCALES[locale]?.dir === 'rtl';
}

export function isValidLocale(code: unknown): code is Locale {
  return typeof code === 'string' && Object.hasOwn(LOCALES, code);
}

